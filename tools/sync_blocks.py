#!/usr/bin/env python3
"""Write the fixed "Levels and layers" block at the end of every SKILL.md.

The block is generated from `tools/templates/fixed-block.md`, with the name
of the skill and the measured size of each level filled in. It sits between
two marker lines; nothing between them is edited by hand.

    python3 tools/sync_blocks.py           # write or refresh the blocks
    python3 tools/sync_blocks.py --check   # exit 1 if a block is stale

Sizes are estimates: characters divided by 3.2, rounded to a thousand
tokens, which is about what this kind of text (tables, numbers, identifiers)
costs. The sweep line comes from the hub's `references/sweeps.tsv` (written
by `promote.py <skill> sweep`). A skill without a `references/` directory is a workflow skill (for
example `cosmoskill-refine`): it has no levels, and gets no block.
Standard library only.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from layout import SKILLS  # noqa: E402
TEMPLATE = Path(__file__).resolve().parent / "templates" / "fixed-block.md"
START = "<!-- cosmoskill:block:start — generated by tools/sync_blocks.py, do not edit by hand -->"
END = "<!-- cosmoskill:block:end -->"
CHARS_PER_TOKEN = 3.2
SWEEPS = ROOT / SKILLS / "observational-cosmology" / "references" / "sweeps.tsv"
SWEEP_COLUMNS = ["skill", "swept_to", "adapters", "recorded"]
SHORT = {"physics-and-methods": "methods", "surveys-and-data": "surveys", "open-questions": "open"}


def thousands(characters: int) -> str:
    return f"{max(1, round(characters / CHARS_PER_TOKEN / 1000))}k"


def split(text: str) -> tuple[str, str | None]:
    """Return (text without the block, block body or None)."""
    if START not in text:
        return text.rstrip("\n") + "\n", None
    head, rest = text.split(START, 1)
    body, _, tail = rest.partition(END)
    return (head.rstrip("\n") + "\n" + tail.strip("\n")).rstrip("\n") + "\n", body.strip("\n")


def sweep_line(skill: str, table: Path, snapshot_here: bool = True) -> str:
    """The block's sentence on how far the skill was swept for newer papers, from the hub's `sweeps.tsv`."""
    rows = []
    if table.is_file():
        lines = table.read_text(encoding="utf-8").splitlines()
        if lines and lines[0].split("\t") == SWEEP_COLUMNS:
            rows = [dict(zip(SWEEP_COLUMNS, (field.strip() for field in line.split("\t"))))
                    for line in lines[1:] if line.strip()]
    rows = [row for row in rows if row.get("skill") == skill and row.get("swept_to")]
    if rows:
        row = max(rows, key=lambda found: found["swept_to"])
        adapters = ", ".join(name for name in row.get("adapters", "").split(",") if name)
        return f"Swept for newer papers up to {row['swept_to']} ({adapters})."
    if snapshot_here:
        return "Not swept for newer papers since the snapshot at the top of this file."
    return "Not swept for newer papers since the snapshot of the suite."


def block_for(skill: Path) -> str:
    own, _ = split((skill / "SKILL.md").read_text(encoding="utf-8"))
    template = TEMPLATE.read_text(encoding="utf-8").strip("\n")
    # A run's `_progress.md` checkpoint is not a level of the skill.
    references = sorted(p for p in (skill / "references").glob("*.md") if not p.name.startswith("_")) \
        if (skill / "references").is_dir() else []
    dossiers = sorted(p for p in (skill / "deep").glob("*.md") if not p.name.startswith("_")) \
        if (skill / "deep").is_dir() else []
    # The block itself is part of L1: count the file as it will be written.
    sizes = [f"L1 {thousands(len(own) + len(template) + 200)}"]
    sizes += [f"{SHORT.get(path.stem, path.stem)} {thousands(len(path.read_text(encoding='utf-8')))}" for path in references]
    sizes += [f"deep/{path.stem} {thousands(len(path.read_text(encoding='utf-8')))}" for path in dossiers]
    deep = ("how a result is obtained and how to choose a method" if dossiers
            else "none in this skill yet: say so and answer at L2")
    sweep = sweep_line(skill.name, SWEEPS, snapshot_here="Snapshot 20" in own)
    return (template.replace("{skill}", skill.name).replace("{sizes}", "; ".join(sizes)).replace("{deep}", deep)
            .replace("{sweep}", sweep))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = 0
    for skill in sorted(p for p in (ROOT / SKILLS).iterdir() if (p / "SKILL.md").is_file() and (p / "references").is_dir()):
        path = skill / "SKILL.md"
        text = path.read_text(encoding="utf-8")
        own, current = split(text)
        wanted = block_for(skill)
        if current == wanted and text.rstrip("\n").endswith(END):
            continue
        stale += 1
        if args.check:
            print(f"{path.relative_to(ROOT)}: block missing or stale")
        else:
            path.write_text(f"{own}\n{START}\n{wanted}\n{END}\n", encoding="utf-8")
            print(f"wrote  {path.relative_to(ROOT)}")
    print(f"{stale} block(s) {'stale' if args.check else 'written'}", file=sys.stderr)
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
