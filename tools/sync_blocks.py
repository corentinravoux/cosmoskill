#!/usr/bin/env python3
"""Write the fixed "Levels and layers" block at the end of every SKILL.md.

The block is generated from `tools/templates/fixed-block.md`, with the name
of the skill and the measured size of each level filled in. It sits between
two marker lines; nothing between them is edited by hand.

    python3 tools/sync_blocks.py           # write or refresh the blocks
    python3 tools/sync_blocks.py --check   # exit 1 if a block is stale

Sizes are estimates: characters divided by 3.2, rounded to a thousand
tokens, which is about what this kind of text (tables, numbers, identifiers)
costs. Standard library only.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = Path(__file__).resolve().parent / "templates" / "fixed-block.md"
START = "<!-- cosmoskill:block:start — generated by tools/sync_blocks.py, do not edit by hand -->"
END = "<!-- cosmoskill:block:end -->"
CHARS_PER_TOKEN = 3.2
SHORT = {"physics-and-methods": "methods", "surveys-and-data": "surveys", "open-questions": "open"}


def thousands(characters: int) -> str:
    return f"{max(1, round(characters / CHARS_PER_TOKEN / 1000))}k"


def split(text: str) -> tuple[str, str | None]:
    """Return (text without the block, block body or None)."""
    if START not in text:
        return text.rstrip("\n") + "\n", None
    head, rest = text.split(START, 1)
    body, _, tail = rest.partition(END)
    return (head.rstrip("\n") + "\n" + tail.strip("\n")).rstrip("\n") + "\n", body.strip("\n")


def block_for(skill: Path) -> str:
    own, _ = split((skill / "SKILL.md").read_text(encoding="utf-8"))
    template = TEMPLATE.read_text(encoding="utf-8").strip("\n")
    references = sorted((skill / "references").glob("*.md")) if (skill / "references").is_dir() else []
    dossiers = sorted((skill / "deep").glob("*.md")) if (skill / "deep").is_dir() else []
    # The block itself is part of L1: count the file as it will be written.
    sizes = [f"L1 {thousands(len(own) + len(template) + 200)}"]
    sizes += [f"{SHORT.get(path.stem, path.stem)} {thousands(len(path.read_text(encoding='utf-8')))}" for path in references]
    sizes += [f"deep/{path.stem} {thousands(len(path.read_text(encoding='utf-8')))}" for path in dossiers]
    deep = ("how a result is obtained and how to choose a method" if dossiers
            else "none in this skill yet: say so and answer at L2")
    return (template.replace("{skill}", skill.name).replace("{sizes}", "; ".join(sizes)).replace("{deep}", deep))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = 0
    for skill in sorted(p for p in (ROOT / "skills").iterdir() if (p / "SKILL.md").is_file()):
        path = skill / "SKILL.md"
        text = path.read_text(encoding="utf-8")
        own, current = split(text)
        wanted = block_for(skill)
        if current == wanted and text.rstrip("\n").endswith(END):
            continue
        stale += 1
        if args.check:
            print(f"{path.relative_to(ROOT)}: block missing or stale")
        else:
            path.write_text(f"{own}\n{START}\n{wanted}\n{END}\n", encoding="utf-8")
            print(f"wrote  {path.relative_to(ROOT)}")
    print(f"{stale} block(s) {'stale' if args.check else 'written'}", file=sys.stderr)
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
